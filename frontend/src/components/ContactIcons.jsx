// Quick lookup: tailwind name -> hex
export const TAILWIND_COLOR_HEX = Object.fromEntries(
  COLOR_PRESETS.map((c) => [c.value, c.hex])
);

// Resolve a stored color (tailwind name OR hex) to a CSS hex value
export function resolveColor(color, fallback = "#06b6d4") {
  if (!color) return fallback;
  if (color.startsWith("#")) return color;
  return TAILWIND_COLOR_HEX[color] || fallback;
}

